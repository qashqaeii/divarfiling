User = get_user_model()


def persian_to_slug(text):
    """
    تبدیل متن فارسی به اسلاگ معتبر
    """
    if not text:
        return ''
    
    # جدول تبدیل کاراکترهای فارسی به انگلیسی
    persian_to_english = {
        'ا': 'a', 'آ': 'a', 'أ': 'a', 'إ': 'a', 'ء': 'a',
        'ب': 'b', 'پ': 'p', 'ت': 't', 'ث': 's', 'ج': 'j',
        'چ': 'ch', 'ح': 'h', 'خ': 'kh', 'د': 'd', 'ذ': 'z',
        'ر': 'r', 'ز': 'z', 'ژ': 'zh', 'س': 's', 'ش': 'sh',
        'ص': 's', 'ض': 'z', 'ط': 't', 'ظ': 'z', 'ع': 'a',
        'غ': 'gh', 'ف': 'f', 'ق': 'gh', 'ک': 'k', 'گ': 'g',
        'ل': 'l', 'م': 'm', 'ن': 'n', 'و': 'v', 'ه': 'h',
        'ی': 'y', 'ي': 'y', 'ئ': 'y', 'ة': 'h', 'ك': 'k',
        '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4',
        '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9',
    }
    
    # تبدیل کاراکترهای فارسی
    result = ''
    for char in text:
        if char in persian_to_english:
            result += persian_to_english[char]
        elif char.isalnum() or char in ['-', '_', ' ']:
            result += char
        else:
            result += ' '
    
    # استفاده از slugify برای تبدیل به فرمت استاندارد
    result = slugify(result)
    
    # حذف خط فاصله‌های اضافی
    result = re.sub(r'-+', '-', result).strip('-')
    
    return result


class Command(BaseCommand):
    help = 'ایجاد یک مقاله حرفه‌ای و SEO شده در مورد ربات تحلیل املاک دیوار'

    def add_arguments(self, parser):
        parser.add_argument(
            '--author-username',
            type=str,
            default='admin',
            help='نام کاربری نویسنده مقاله (پیش‌فرض: admin)',
        )
        parser.add_argument(
            '--publish',
            action='store_true',
            help='مقاله را بلافاصله منتشر کند',
        )

    def handle(self, *args, **options):
        self.stdout.write(self.style.SUCCESS('شروع ایجاد مقاله حرفه‌ای...'))
        
        # دریافت یا ایجاد نویسنده
        try:
            author = User.objects.get(username=options['author_username'])
        except User.DoesNotExist:
            self.stdout.write(self.style.ERROR(f'کاربر با نام کاربری "{options["author_username"]}" یافت نشد.'))
            self.stdout.write(self.style.WARNING('در حال ایجاد کاربر ادمین...'))
            author = User.objects.create_superuser(
                username=options['author_username'],
                email='admin@example.com',
                password='admin123'
            )
            self.stdout.write(self.style.SUCCESS(f'کاربر "{author.username}" ایجاد شد.'))
        
        # ایجاد یا دریافت دسته‌بندی
        category, created = Category.objects.get_or_create(
            slug='robots-automation',
            defaults={
                'name': 'ربات‌ها و اتوماسیون',
                'description': 'مقالات مربوط به ربات‌ها، اتوماسیون و هوش مصنوعی',
                'order': 1,
            }
        )
        if created:
            self.stdout.write(self.style.SUCCESS(f'دسته‌بندی "{category.name}" ایجاد شد.'))
        else:
            self.stdout.write(self.style.WARNING(f'دسته‌بندی "{category.name}" از قبل وجود داشت.'))
        
        # ایجاد یا دریافت برچسب‌ها
        tag_names = [
            'ربات دیوار',
            'تحلیل املاک',
            'استخراج داده',
            'هوش مصنوعی',
            'اتوماسیون',
            'وب اسکرپینگ',
            'تحلیل داده',
            'املاک و مستغلات',
            'دیوار',
            'ابزار تحلیلی',
        ]
        
        tags = []
        for tag_name in tag_names:
            tag, created = Tag.objects.get_or_create(
                slug=persian_to_slug(tag_name),
                defaults={'name': tag_name}
            )
            if created:
                self.stdout.write(self.style.SUCCESS(f'برچسب "{tag.name}" ایجاد شد.'))
            tags.append(tag)
        
        # محتوای مقاله
        title = 'ربات هوشمند تحلیل املاک دیوار: راهکار کامل برای استخراج و تحلیل داده‌های املاک'
        slug = persian_to_slug(title)
        
        # بررسی یکتایی slug
        base_slug = slug
        counter = 1
        while Post.objects.filter(slug=slug).exists():
            slug = f'{base_slug}-{counter}'
            counter += 1
        
        excerpt = 'ربات هوشمند تحلیل املاک دیوار یک ابزار پیشرفته و حرفه‌ای برای استخراج، پردازش و تحلیل داده‌های آگهی‌های املاک از وب‌سایت دیوار است. این ربات با استفاده از تکنولوژی‌های مدرن، فرآیند جمع‌آوری و تحلیل اطلاعات املاک را به صورت خودکار انجام می‌دهد.'
        
        content = self.get_article_content()
        
        # ایجاد یا به‌روزرسانی مقاله
        post, created = Post.objects.get_or_create(
            slug=slug,
            defaults={
                'title': title,
                'author': author,
                'category': category,
                'content': content,
                'excerpt': excerpt,
                'is_published': options['publish'],
                'published_at': timezone.now() if options['publish'] else None,
            }
        )
        
        if created:
            self.stdout.write(self.style.SUCCESS(f'مقاله "{post.title}" ایجاد شد.'))
        else:
            self.stdout.write(self.style.WARNING(f'مقاله "{post.title}" از قبل وجود داشت. به‌روزرسانی شد.'))
            post.title = title
            post.content = content
            post.excerpt = excerpt
            post.category = category
            if options['publish']:
                post.is_published = True
                post.published_at = timezone.now()
            post.save()
        
        # اضافه کردن برچسب‌ها
        post.tags.set(tags)
        
        self.stdout.write(self.style.SUCCESS('\n✅ مقاله با موفقیت ایجاد شد!'))
        self.stdout.write(self.style.SUCCESS(f'شناسه مقاله: {post.id}'))
        self.stdout.write(self.style.SUCCESS(f'عنوان: {post.title}'))
        self.stdout.write(self.style.SUCCESS(f'نامک: {post.slug}'))
        self.stdout.write(self.style.SUCCESS(f'دسته‌بندی: {post.category.name}'))
        self.stdout.write(self.style.SUCCESS(f'تعداد برچسب‌ها: {post.tags.count()}'))
        self.stdout.write(self.style.SUCCESS(f'وضعیت انتشار: {"منتشر شده" if post.is_published else "پیش‌نویس"}'))
        
        if not post.is_published:
            self.stdout.write(self.style.WARNING('\nبرای انتشار مقاله از پنل ادمین استفاده کنید یا از فلگ --publish استفاده کنید.'))

